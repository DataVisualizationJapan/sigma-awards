export function langsJa(value) {
  if (!value) return "";
  let text = String(value);
  for (const [source, target] of LANG_JA) {
    text = text.replaceAll(new RegExp(source, "gi"), target);
  }
  return text.replace(/\s+/g, " ").trim();
}
